CREATE TABLE public.job_categories (
  slug text PRIMARY KEY,
  name text NOT NULL UNIQUE,
  emoji text NOT NULL,
  sort_order integer NOT NULL UNIQUE,
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.job_professions (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  category_slug text NOT NULL REFERENCES public.job_categories(slug),
  name text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT profession_name_per_category UNIQUE(category_slug,name)
);
CREATE INDEX job_professions_category_idx ON public.job_professions(category_slug);
ALTER TABLE public.job_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.job_professions ENABLE ROW LEVEL SECURITY;
